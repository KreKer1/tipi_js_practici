import assert from 'node:assert/strict';
import { validateTaskDraft } from '../src/form-validation.js';
import { loadTasks, saveTasks } from '../src/task-storage.js';
const draft = { id: '20', title: '  ' + 'я'.repeat(100) + '  ', priority: 'high' };
assert.equal(validateTaskDraft(draft, []).value.title.length, 100);
console.log('OK: граница 100 символов после удаления внешних пробелов');
const values = new Map();
const storage = { getItem: (key) => values.get(key) ?? null, setItem: (key,value) => values.set(key,value) };
const task = { id: 20, title: 'Сохранить дважды', completed: false, priority: 'high' };
assert.equal(saveTasks(storage,'own',[task]).ok,true);
const first = loadTasks(storage,'own',[]);
first.tasks[0].completed = true;
assert.equal(saveTasks(storage,'own',first.tasks).ok,true);
const second = loadTasks(storage,'own',[]);
assert.equal(second.tasks[0].completed,true);
assert.equal(task.completed,false);
console.log('OK: два цикла сохранения/восстановления сохраняют последнее состояние');
values.set('own',JSON.stringify({version:1,tasks:[task,{...task,id:21,priority:'urgent'}]}));
const fallback = [{...task,id:7}];
const damaged = loadTasks(storage,'own',fallback);
assert.equal(damaged.source,'fallback');
assert.deepEqual(damaged.tasks,fallback);
assert.notEqual(damaged.tasks[0],fallback[0]);
console.log('OK: одна повреждённая задача отклоняет целую запись, fallback независим');
console.log('Собственные проверки: 3/3.');
